"""B16/B17: Hi+ interval 100 -> 80 ms in the RAM table read from the camera (categories 0..2). Uses readcheck.c levels 16/17 unmodified.
Builds, then runs both libraries in Unicorn against the bytes the camera reported.
  zve1fw\\.venv_build\\Scripts\\python.exe -I -B build_burst80.py
"""
import hashlib, shutil, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = Path(__file__).resolve().parents[3]
CT6 = REPO / "windows/tools/camera_tests/CT6_memory_read_check"
SEN = Path(r"zve1fw\out\firmware.tar_unpacked\0700_part_image\dev\nflasha15_unpacked\lib\libsencore.so")
READ = REPO / "windows/camera_private/CT6_20261125T232708Z_zv_oneshot_burst_read/01_BR_readcheck_result.txt"
NAME, NEW_MS, TAB = "burst80_zv_v1", 80, 0x1A08998

got = {l.split()[1]: (int(l.split()[2], 16), bytes.fromhex(l.split()[3])) for l in READ.read_text().splitlines() if l.startswith("data ")}
base, blob = got["interval_tab"]
cam = lambda a, n: blob[a - base:a - base + n]
SITES = []
for cat in range(3):
    a = TAB + 16 * cat
    old = cam(a, 4)
    assert old[0] == old[1] == 100, (cat, old)
    SITES.append((a, old, bytes([NEW_MS, NEW_MS]) + old[2:]))
GUARDS = [(TAB + 16 * cat + 4, cam(TAB + 16 * cat + 4, 12)) for cat in range(3)] + [(TAB + 48, cam(TAB + 48, 8))]
assert cam(TAB + 4, 4) == bytes.fromhex("a600a600")


def build():
    hx = lambda b: ", ".join("0x%02x" % x for x in b)
    out = ["/* Generated by build_burst80.py from %s. Do not edit. */" % READ.parent.name, '#define WORDS_DESIGN "%s"' % NAME,
           "struct ram_word { u32 address; u8 stock[4]; u8 changed[4]; };", "static const struct ram_word ram_words[] = {"]
    out += ["    { 0x%x, { %s }, { %s } }," % (a, hx(o), hx(n)) for a, o, n in SITES]
    out += ["};", "struct ram_guard { u32 address; u32 len; u8 bytes[16]; };", "static const struct ram_guard ram_guards[] = {"]
    out += ["    { 0x%x, %d, { %s } }," % (a, len(b), hx(b.ljust(16, b"\0"))) for a, b in GUARDS]
    (HERE / f"expected_words_{NAME}.h").write_text("\n".join(out + ["};"]) + "\n", encoding="ascii")
    built = {}
    for lvl in (16, 17):
        so = HERE / f"libJit_zv_B{lvl}.so"
        subprocess.run([sys.executable, "-m", "ziglang", "cc", "-target", "aarch64-linux-gnu", "-std=gnu11", "-O1", "-Wall", "-Wextra", "-Werror",
                        "-fPIC", "-shared", "-nostdlib", "-ffreestanding", "-fno-stack-protector", "-fno-builtin", "-fno-asynchronous-unwind-tables",
                        "-Wl,-soname,libJit.so", "-Wl,--no-undefined", "-Wl,-z,now", "-g0", "-s", "-Wl,-z,max-page-size=4096", f"-DLEVEL={lvl}",
                        f'-DWORDS_H="expected_words_{NAME}.h"', "-I", str(HERE), str(CT6 / "helper/readcheck.c"), str(SEN), "-o", str(so)],
                       check=True, cwd=HERE, capture_output=True)
        built[lvl] = so
    return built


def test(built):
    sys.path.insert(0, r"zve1fw\pal25")
    import verify_pal25_emu as E          # its AArch64 harness: DMA, /dev/mem, result file
    l16, l17 = (E.parse_and_audit_elf(built[k]) for k in (16, 17))
    stock = bytearray(E.CP_RAM_SIZE)
    for a, b in got.values():
        stock[a - E.CP_RAM_BASE:a - E.CP_RAM_BASE + len(b)] = b
    want = bytearray(stock)
    for a, _, n in SITES:
        want[a - E.CP_RAM_BASE:a - E.CP_RAM_BASE + 4] = n
    assert sum(x != y for x, y in zip(stock, want)) == 6

    ram = bytearray(stock)
    rep, st = E.run_elf_on_ram(l16, ram)
    assert rep.startswith("readcheck 1 level 16\n") and "DONE: every site holds the target bytes (apply)" in rep and ram == want, rep
    print("PASS apply: exactly 6 bytes change (100 -> 80, three categories)")
    rep, st = E.run_elf_on_ram(l16, ram)
    assert "NOTHING TO DO" in rep and not st["dma_writes"] and ram == want, rep
    print("PASS re-apply: nothing written")
    rep, _ = E.run_elf_on_ram(l17, ram)
    assert "DONE: every site holds the target bytes (put back)" in rep and ram == stock, rep
    print("PASS put back: bit-exact")
    for what, at in [("guard", a) for a, _ in GUARDS] + [("site", a + 2) for a, _, _ in SITES]:
        bad = bytearray(stock)
        bad[at - E.CP_RAM_BASE] ^= 1
        before = bytes(bad)
        rep, st = E.run_elf_on_ram(l16, bad)
        assert "nothing is written" in rep and not st["dma_writes"] and bytes(bad) == before, (what, rep)
    print("PASS refusal: any changed guard or site byte -> 0 writes (%d cases)" % (len(GUARDS) + len(SITES)))
    for lib, start in ((l16, stock), (l17, want)):
        for n in (1, 2, 3):
            ram = bytearray(start)
            rep, _ = E.run_elf_on_ram(lib, ram, fail_on_write_num=n)
            assert "NOT DONE: a step failed" in rep and ram == start, (n, rep)
    print("PASS rollback: a failure at each of the 3 writes, apply and put back, restores bit-exact")


if __name__ == "__main__":
    built = build()
    test(built)
    for lvl, so in built.items():
        shutil.copy2(so, CT6 / "helper_zv_custom" / so.name)
        print(hashlib.sha256(so.read_bytes()).hexdigest(), so.stat().st_size, so.name)
