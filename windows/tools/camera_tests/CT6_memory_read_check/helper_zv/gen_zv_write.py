"""Write the headers the A7 IV helper (helper/readcheck.c) needs to carry the ZV-E1 2.02 designs (ZV-E1 port of the A7S III kit, 2026-11-24).

  work/venv/Scripts/python.exe -I -B gen_zv_write.py

Made from helper_c2/gen_c2_write.py (the A7C II's: the same 0x170-byte stored record and appFw.so cave in .rela.dyn), with this build's
files, addresses and designs (modding/ZVE1_PORT.md). The write levels of readcheck.c are used as they are; only their tables and a few
constants differ (helper_zv/build_zv_write.sh passes those). This writes, into helper/, in gen_expected.py's formats:
  expected_dmm_dmmwb_zv_v1.h               levels 13/14: the movie raw write buffer's size word, its unit record and the parent's records
  expected_sites_ogsq_zv_v2.h              levels 5/6: 21 sensor/record sites and the changed bytes of the 0x170-byte stored record
  expected_words_outsz2560_zv_v1.h         levels 16/17: the output-size word and its guards
  expected_words_lcdfill_zv_v2.h           levels 16/17: the rear screen at 3:2 with the focus frames (fit word, two frame tables)
  expected_mp_ogfile2560_hs_s_zv_v1.h      levels 19/20: encoder-side sites in av-cam.bin and libmpr.so
  expected_mp_lcdcycle_zv_v1.h             levels 19/20: the C2 preview routine in appFw.so
Every stock byte is compared with the 2.02 files here.
DMM step (levels 13/14, added after the first ZV-E1 test, 2026-11-23): the A7S III kit has none, because its raw write buffer holds a full-height
frame; the ZV-E1's holds only the stock 4K stage (4288 x 2408), which restarted the camera. build/build_dmm_zv.py has the design.
"""
import hashlib
import json
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "helper"
ROOT = HERE.parents[2]
EX = ROOT / "work/extracted/zve1_202/0700_part_image/dev"
DES = ROOT / "modding/designs"
sys.path.insert(0, str(ROOT / "build"))
import parse_dmmcfg  # noqa: E402

BASE = 0x108000
IMAGE = (EX / "nflasha8/cpapp-b.bin").read_bytes()
IMAGE_END = BASE + len(IMAGE)
# av-cam.bin and libmpr.so tables (build/build_ogfile.py, entry zve1_202): the descriptor table has 647 rows of 0x88 bytes on this body
DESC, DSIZE, UNIT, CLIP, COMB = 0x38F8E8, 0x88, 0x38F848, 0x38D7EC, 0x2D32B8 - 0x205C0
PROFILE_END = 0x3BAEA0 + 299 * 0x100
REC = 0x170
DATA_LO = 0xD00000                                 # every cpapp-b.bin site of this kit lies in the tables from here (ZV-E1 code reaches 0xc0xxxx)
hx = lambda b: ", ".join("0x%02x" % x for x in b)
HEAD = "/* Generated by helper_zv/gen_zv_write.py from modding/designs/%s.json (ZV-E1 2.02). Do not edit. */"


def sites_header(name):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    assert d["build"] == "zve1_202" and d["artifact_sha256"] == hashlib.sha256(IMAGE).hexdigest()
    sites = sorted((int(p["addr"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])) for p in d["patches"])
    out = [HEAD % name, "/* %d sites, %d bytes. Stock bytes were compared with cpapp-b.bin %s. */" % (len(sites), sum(len(o) for _, o, _ in sites), d["artifact_sha256"][:16])]
    rows = []
    for k, (a, old, new) in enumerate(sites):
        assert len(old) == len(new) and old != new and IMAGE[a - BASE:a - BASE + len(old)] == old
        lo, hi = a & ~63, (a + len(old) + 63) & ~63
        assert hi - lo <= 4096 and DATA_LO <= lo and hi <= IMAGE_END, "span outside the image's tables"
        for tag, data in (("old", old), ("new", new)):
            out.append("static const u8 site%d_%s[%d] = { %s };" % (k, tag, len(data), hx(data)))
        rows.append("    { 0x%x, %d, site%d_old, site%d_new, 0, 0 }," % (a, len(old), k, k))
    assert all(a + len(o) <= b for (a, o, _), (b, _, _) in zip(sites, sites[1:])), "sites overlap"
    assert d["record_size"] == REC
    r_stock, r_new = bytes.fromhex(d["stored_record"]["stock"]), bytes.fromhex(d["stored_record"]["design"])
    offs = [k for k in range(REC) if r_stock[k] != r_new[k]]
    assert len(r_stock) == len(r_new) == REC and offs[:2] == [6, 7] and r_stock[6] == r_stock[7] == 1 and 2 < len(offs) <= 128
    out += ["static const unsigned short rec_offs[%d] = { %s };" % (len(offs), ", ".join("0x%x" % k for k in offs)),
            "static const u8 rec_stock[%d] = { %s };" % (len(offs), hx(bytes(r_stock[k] for k in offs))),
            "static const u8 rec_new[%d] = { %s };" % (len(offs), hx(bytes(r_new[k] for k in offs))),
            "#define REC_BYTES %d" % len(offs),
            '#define SITES_TEXT "%d"' % len(sites), '#define ALL_TEXT "%d"' % (len(sites) + 1),
            "#define MODE_ID %sU" % d["mode_id"], '#define MODE_TEXT "%s"' % d["mode_id"],
            "/* offs: null for a site whose `length` bytes all change; else the offsets, inside `length` bytes, of the noffs bytes that change. */",
            "struct cp_site { u64 address; u32 length; const u8 *stock; const u8 *changed; const unsigned short *offs; u32 noffs; };",
            "static const struct cp_site cp_sites[] = {"] + rows + ["};"]
    (OUT / f"expected_sites_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), len(offs), d["mode_id"]


def dmm_header(name="dmmwb_zv_v1"):
    """gen_c2_write.dmm_header for this body's one-word design: the size of the single key 0x57f record (group 0x89, parent key 0x38). No layout
    is steered, so the header has one site, one record, the two records of the parent key 0x38, fit {size, 1} and the busy key 0x57f only."""
    design = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    assert design["build"] == "zve1_202"
    cfg = parse_dmmcfg.Config(parse_dmmcfg.find_file("zve1_202"), "zve1_202")
    ram = lambda u: cfg.ram("unit_records", u["seq"] * 0x14)
    by_ram = {ram(u): u for g in cfg.groups for u in g["units"]}
    sites, recs = [], []
    for st in design["sites"]:
        a, old, new = int(st["ram_address"], 16), bytes.fromhex(st["old"]), bytes.fromhex(st["new"])
        rec = next(r for r in by_ram if r <= a < r + 0x14)
        u, off = by_ram[rec], a - rec
        assert len(old) == len(new) == 4 and old != new and off == 12 and (a & 63) <= 60
        assert u["key"] == 0x57F and u["group"]["gid"] == 0x89 and cfg.data[u["at"] + off:u["at"] + off + 4] == old
        sites.append((a, old, new))
        recs.append((rec, off, cfg.data[u["at"]:u["at"] + 0x14]))
    new_size = design["summary"]["unit_size"]
    assert len(sites) == 1 and sites[0][2] == new_size.to_bytes(4, "little") and new_size % 128 == 0
    parents = [(ram(u), cfg.data[u["at"]:u["at"] + 0x14]) for u in cfg.units_by_key[0x38]]
    assert len(parents) == 2 and all(u["size"] >= new_size for u in cfg.units_by_key[0x38])
    assert [u["key"] for g in cfg.groups if g["gid"] == 0x89 for u in g["units"]] == [0x57F]
    out = [HEAD % name,
           "/* The memory manager's RAM copy of its unit records (cpapp-b.bin 2.02, 0x257b07c on): %d word in %d record. */" % (len(sites), len(recs)),
           '#define DMM_DESIGN "%s"' % name,
           "/* the new unit size, and how many units of it must fit the parent */",
           "static const u32 dmm_fit[2] = { %dU, 1U };" % new_size,
           "struct dmm_site { u32 address; u8 stock[4]; u8 changed[4]; };",
           "static const struct dmm_site dmm_sites[] = {"]
    out += ["    { 0x%x, { %s }, { %s } }," % (a, hx(old), hx(new)) for a, old, new in sites]
    out += ["};", "/* the record each site lies in, as in the file: every byte but the site's four (from site_off) must equal these */",
            "struct dmm_rec { u32 address; u32 site_off; u8 file[20]; };", "static const struct dmm_rec dmm_recs[] = {"]
    out += ["    { 0x%x, %d, { %s } }," % (r, off, hx(b)) for r, off, b in recs]
    out += ["};", "/* the records of the parent unit (key 0x38): all 20 bytes must equal the file's, and the size must hold a unit of the new size */",
            "static const struct dmm_rec dmm_parents[] = {"]
    out += ["    { 0x%x, 0xff, { %s } }," % (r, hx(b)) for r, b in parents]
    out += ["};", "/* a unit object of this key in a division still in force: nothing is written */",
            "static const u32 dmm_busy_keys[] = { 0x57f };"]
    (OUT / f"expected_dmm_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), [hex(r) for r, _ in parents]


# Where a words design may have a site, and where only a guard (ZV-E1 addresses; build/build_ram_words_zv.py, modding/ZVE1_PORT_PART_A.md)
SIZE_TABLE = (0x1996514, 0x1996514 + 0x80)        # the movie size table, base 0x19964c4 + 0x50
FIT = (0x1F5C84, 0x1F5C90)                         # the VDF fit-mode words of a 16:9 picture (the fit word 0x1f5c88)
FRAMES = ((0xE9B3E0, 0xE9B458), (0xE9B458, 0xE9B4D0))   # cpActAfWindow, cpActTrackingFrame (no remote-send widget on this body)
WORD_REGIONS = {"outsz2560_zv_v1": ((SIZE_TABLE,), ()),
                "lcdfill_zv_v2": ((FIT,) + FRAMES, ((0x1F5C34, 0x1F5CB0),))}   # guards: the fit function and its tables


def words_header(name):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    assert d["kind"] == "ram_words" and d["build"] == "zve1_202"
    sites = [(int(s["ram_address"], 16), bytes.fromhex(s["old"]), bytes.fromhex(s["new"])) for s in d["sites"]]
    guards = [(int(g["ram_address"], 16), bytes.fromhex(g["bytes"])) for g in d["guards"]]
    site_regions, guard_only = WORD_REGIONS[name]
    within = lambda a, n, regions: any(lo <= a and a + n <= hi for lo, hi in regions)
    assert sites and all(len(o) == len(n) == 4 and o != n and a % 4 == 0 and within(a, 4, site_regions) for a, o, n in sites)
    assert guards and all(0 < len(b) <= 16 and within(a, len(b), site_regions + guard_only) for a, b in guards)
    for a, o, _ in sites:                                  # words inside the loaded image: the file's bytes
        if BASE <= a < IMAGE_END:
            assert IMAGE[a - BASE:a - BASE + 4] == o
    for a, b in guards:
        if BASE <= a < IMAGE_END:
            assert IMAGE[a - BASE:a - BASE + len(b)] == b
    assert not any(a < sa + 4 and sa < a + len(b) for a, b in guards for sa, _, _ in sites), "a guard overlaps a site"
    out = [HEAD % name, "/* Words of the coprocessor's RAM tables (cpapp-b.bin 2.02): %d site(s), %d guard(s). */" % (len(sites), len(guards)),
           '#define WORDS_DESIGN "%s"' % name, "struct ram_word { u32 address; u8 stock[4]; u8 changed[4]; };", "static const struct ram_word ram_words[] = {"]
    out += ["    { 0x%x, { %s }, { %s } }," % (a, hx(o), hx(n)) for a, o, n in sites]
    out += ["};", "/* bytes beside the sites that must be as listed before anything is written */",
            "struct ram_guard { u32 address; u32 len; u8 bytes[16]; };", "static const struct ram_guard ram_guards[] = {"]
    out += ["    { 0x%x, %d, { %s } }," % (a, len(b), hx(b.ljust(16, b"\0"))) for a, b in guards]
    out += ["};"]
    (OUT / f"expected_words_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), len(guards)


def av_guards(av):
    g = [(UNIT + 0x20, av[UNIT + 0x20:UNIT + 0x30]), (CLIP + 0x50, av[CLIP + 0x50:CLIP + 0x60])]
    assert struct.unpack("<4I", g[0][1]) == (0x486, 0x474, 0x477, 0x47A) and struct.unpack("<4I", g[1][1]) == (1, 3840, 2160, 23)
    return g


def first_load(lib):
    phoff, phentsize, phnum = struct.unpack_from("<Q", lib, 0x20)[0], *struct.unpack_from("<HH", lib, 0x36)
    load0 = next(struct.unpack_from("<IIQQQQQQ", lib, phoff + k * phentsize) for k in range(phnum) if struct.unpack_from("<I", lib, phoff + k * phentsize)[0] == 1)
    assert load0[2] == 0 and load0[3] == 0
    return load0


def mp_header(name):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    av, lm = (EX / "nflasha3/av-cam.bin").read_bytes(), (EX / "nflasha15/lib/libmpr.so").read_bytes()
    assert d.get("build") == "zve1_202"
    assert d["artifact_sha256"] == {"libmpr.so": hashlib.sha256(lm).hexdigest(), "av-cam.bin": hashlib.sha256(av).hexdigest()}
    assert not any(p["code"] for p in d["patches"]), "not a data-only design"
    tabs = {"av-cam.bin": [], "libmpr.so": []}
    for p in d["patches"]:
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        data = av if p["binary"] == "av-cam.bin" else lm
        assert len(old) == len(new) <= 16 and old != new and data[off:off + len(old)] == old
        tabs[p["binary"]].append((off, 1, old, new))
    g_av = av_guards(av)
    for x in d["descriptors"]:
        o = DESC + x["descriptor"] * DSIZE + 0x28
        assert struct.unpack_from("<I", av, o)[0] == x["profile_key"]
        g_av.append((o, av[o:o + 4]))
    g_lm = [(0, lm[:16])]
    for off, _, old, new in tabs["libmpr.so"]:
        if len(old) == 4:                                        # a site that is the row's whole raster (width and height): the guard is the codec before it
            assert (off - 4 - COMB) % 0x18 == 0 and struct.unpack("<HH", old) == (3840, 2160)
            g_lm.append((off - 4, lm[off - 4:off]))
            continue
        assert (off - 6 - COMB) % 0x18 == 0 and struct.unpack_from("<H", lm, off - 2)[0] == 3840
        g_lm.append((off - 6, lm[off - 6:off]))
    for binary, guards in (("av-cam.bin", g_av), ("libmpr.so", g_lm)):
        sites = tabs[binary]
        assert not any(a < s + len(o) and s < a + len(b) for a, b in guards for s, _, o, _ in sites), "a guard overlaps a site"
        tabs[binary] = sorted(sites + [(a, 0, b, b"") for a, b in guards])
        assert all(tabs[binary][k][0] + len(tabs[binary][k][2]) <= tabs[binary][k + 1][0] for k in range(len(tabs[binary]) - 1)), "entries overlap"
    first = tabs["av-cam.bin"][0][0] & ~0xFFF
    last = max(a + len(o) for a, _, o, _ in tabs["av-cam.bin"])
    span = ((last - first) + 0xFFF) & ~0xFFF
    assert (CLIP & ~0xFFF) <= first and first + span <= ((PROFILE_END + 0xFFF) & ~0xFFF), "an av-cam.bin site lies outside the pages of its tables"
    load0 = first_load(lm)
    assert max(a + len(o) for a, _, o, _ in tabs["libmpr.so"]) <= load0[5], "a libmpr.so site lies outside the first segment"
    h16 = lambda b: hx(b.ljust(16, b"\0"))
    out = [HEAD % name,
           "/* av-cam.bin %s..., libmpr.so %s... (2.01). kind 1: a site of the design; kind 0: a guard, bytes that must be as in the file. */"
           % (d["artifact_sha256"]["av-cam.bin"][:16], d["artifact_sha256"]["libmpr.so"][:16]),
           '#define MP_DESIGN "%s"' % name,
           "#define MP_AV_FIRST 0x%xUL                 /* file offset of the first page read of av-cam.bin */" % first,
           "#define MP_AV_BYTES 0x%xUL                  /* whole pages: every entry of mp_av lies inside */" % span,
           "struct mp_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };"]
    longest = max(len(tabs["av-cam.bin"]), len(tabs["libmpr.so"]))
    if longest > 96:
        out.insert(-1, "#define MP_MAX %d                          /* room for the entries of the longer table (levels 19 and 20) */" % ((longest + 31) & ~31))
    for binary, var in (("av-cam.bin", "mp_av"), ("libmpr.so", "mp_lm")):
        out.append("static const struct mp_site %s[] = {      /* %s: file offsets */" % (var, binary))
        out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in tabs[binary]]
        out.append("};")
    (OUT / f"expected_mp_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return {b: (sum(1 for e in t if e[1] == 1), sum(1 for e in t if e[1] == 0)) for b, t in tabs.items()}, hex(first), hex(span)


def mp_appfw_header(name="lcdcycle_zv_v1"):
    """An appFw.so design (build/build_lcdcycle_zv.py): code sites written in the design's order (the cave before the hook), put back in reverse
    (MP_LM_ORDERED). Guards: the file's first 16 bytes, 16 file bytes just before the cave, 16 bytes on each side of the hooked instruction, and the
    first 16 bytes of each function the routine calls (the design's "calls")."""
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    av, lib = (EX / "nflasha3/av-cam.bin").read_bytes(), (EX / "nflasha15/lib/appFw.so").read_bytes()
    assert d["library"] == "appFw.so" and all(p["binary"] == "appFw.so" and p["code"] for p in d["patches"])
    assert d["artifact_sha256"] == {"appFw.so": hashlib.sha256(lib).hexdigest()}, "the design was made from another appFw.so"
    g_av = av_guards(av)
    load0 = first_load(lib)
    mapped = (load0[5] + 0xFFF) & ~0xFFF                 # the mapping at offset 0 holds whole pages
    assert mapped == 0x4AFB000
    RELA = (0xF3E0, 0x17D8150)
    assert struct.unpack_from("<Q", lib, RELA[0] + 8)[0] and lib.find(b".rela.dyn") >= 0
    sites = []
    for p in d["patches"]:
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        assert len(old) == len(new) <= 16 and old != new and lib[off:off + len(old)] == old and off + len(old) <= mapped
        # ZV-E1: the cave is inside .rela.dyn (DT_RELA 0xf3e0 .. DT_JMPREL 0x17d8150), as on the A7C II, in the first r-x mapping: relocation entries the loader
        # applies once at load (R_AARCH64_ABS64 only, no DT_TEXTREL, lazily bound .rela.plt after it); appFw's own tail has only 768 bytes.
        assert p["kind"] == "hook" or (p["kind"] == "cave" and RELA[0] <= off and off + len(old) <= RELA[1]), p
        sites.append((off, 1, old, new))
    hooks = [s for s, p in zip(sites, d["patches"]) if p["kind"] == "hook"]
    cave0 = min(s[0] for s, p in zip(sites, d["patches"]) if p["kind"] == "cave")
    assert len(hooks) == 1 and d["patches"][-1]["kind"] == "hook", "the hook must come last (apply order)"
    g_lib = [(0, lib[:16]), (cave0 - 0x18, lib[cave0 - 0x18:cave0 - 8])]
    for off, _, _, _ in hooks:
        g_lib += [(off - 16, lib[off - 16:off]), (off + 4, lib[off + 4:off + 20])]
    for fn in sorted(int(v, 16) for v in d.get("calls", {}).values()):
        g_lib.append((fn, lib[fn:fn + 16]))
    srt = sorted(sites + [(a, 0, b, b"") for a, b in g_lib])
    assert all(srt[k][0] + len(srt[k][2]) <= srt[k + 1][0] for k in range(len(srt) - 1)), "entries overlap"
    table = [(a, 0, b, b"") for a, b in g_lib] + sites
    h16 = lambda b: hx(b.ljust(16, b"\0"))
    avs = sorted((a, 0, b, b"") for a, b in g_av)
    first = avs[0][0] & ~0xFFF
    span = ((max(a + len(b) for a, _, b, _ in avs) - first) + 0xFFF) & ~0xFFF
    out = [HEAD % name,
           "/* appFw.so %s... (2.02). kind 1: a site of the design; kind 0: a guard, bytes that must be as in the file. */" % d["artifact_sha256"]["appFw.so"][:16],
           '#define MP_DESIGN "%s"' % name, '#define MP_LIB "appFw.so"                 /* the mp_lm table is in appFw.so */',
           "#define MP_LM_ORDERED 1                    /* mp_lm sites in apply order (cave, then the hook); put back in reverse */",
           "#define MP_AV_FIRST 0x%xUL                 /* av-cam.bin: two guards only, nothing written there */" % first, "#define MP_AV_BYTES 0x%xUL" % span]
    if len(table) > 96:
        out.append("#define MP_MAX %d                         /* room for the entries of the appFw.so table (levels 19 and 20) */" % ((len(table) + 31) & ~31))
    out.append("struct mp_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };")
    for var, rows, what in (("mp_av", avs, "av-cam.bin"), ("mp_lm", table, "appFw.so")):
        out.append("static const struct mp_site %s[] = {      /* %s: file offsets */" % (var, what))
        out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in rows]
        out.append("};")
    (OUT / f"expected_mp_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return {"sites": len(sites), "hooks": len(hooks), "guards": len(g_lib), "mapped": hex(mapped), "cave": hex(cave0)}


